/**
 * ⚠ THE DEV-ONLY DEMONSTRATION GATE. The populated-demo dev site breaks a dozen
 * extra classes into illustrative units so the grid reads as finished. Those
 * units are GENERATED (`demo-units.generated.ts`) and merged in ONLY when the
 * server-side `IDA_DEMO_CURRICULUM` flag is set — which only the dev frontend
 * deployment does. This gate is load-bearing, not cosmetic: the demo classes
 * (AC 210, ST 260, …) ALSO exist in the real `majors.yaml`, so if the demo
 * taxonomy were merged in prod their unit titles would render against those real
 * (unmeasured) classes. Kept off in staging/prod, the demo units never load and
 * every real class there reads exactly as it does today.
 *
 * ⚠ ONE READER OF THE GATE. The demo-curriculum merge and the suppression of the
 * demonstration tells are two faces of the same fact — "this is the dev preview"
 * — so they read the same env through the same function (`isDevDemoPreview`)
 * rather than two copies that could drift. See `lib/preview.ts` for the
 * prod-safety contract and why it is read at call time in a try/catch.
 */
const demoCurriculumEnabled = isDevDemoPreview;

/** The taxonomy this request sees: the real one, plus the demo classes when the
 * dev gate is on. MIS 200 is only ever in the real set, so the merge cannot
 * shadow or alter it. */
function taxonomy(): Record<string, ClassUnit[]> {
  return demoCurriculumEnabled() ? { ...TAXONOMY, ...DEMO_TAXONOMY } : TAXONOMY;
}

/** The units a class defines, in course order. Empty for a class with no
 * taxonomy yet — the class page renders that honestly. */
export function unitsFor(course: string): ClassUnit[] {
  return taxonomy()[course] ?? [];
}

/** Does this class have a unit breakdown at all? */
export function hasUnits(course: string): boolean {
  return (taxonomy()[course]?.length ?? 0) > 0;
}

/** One unit of one class, by its URL key. Case-insensitive on the key so a
 * hand-typed URL still resolves. */
export function findUnit(course: string, key: string): ClassUnit | undefined {
  const wanted = key.toLowerCase();
  return unitsFor(course).find((unit) => unit.key.toLowerCase() === wanted);
}

/** The unit's title, or the raw key when the class defines no such unit — never
 * a thrown error on a bad URL segment. */
export function unitTitle(course: string, key: string): string {
  return findUnit(course, key)?.title ?? key;
}

/** Every course code that carries a unit taxonomy. For tests and guards. */
export function coursesWithUnits(): string[] {
  return Object.keys(taxonomy());
}
